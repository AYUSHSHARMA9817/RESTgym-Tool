"""Turn the raw evaluation data into the paper's tables and number macros.
Every number in the paper is printed by this script; nothing is typed by hand.

Usage: python3 -m eval.summarize ../paper/data ../paper
Reads  DATA/parser.csv, DATA/conformance.csv, DATA/cost.csv, DATA/live/<api>/<config>-<rep>.json
Writes PAPER/tables/{parser,live}.tex and PAPER/data/numbers.tex
"""
import csv
import glob
import json
import os
import statistics
import sys

CONFIGS = ["baseline", "values", "values+pool", "full"]
CONFIG_LABEL = {"baseline": "Baseline", "values": "+Values", "values+pool": "+Pool", "full": "+Order (full)"}
MOTIVATING_OP = "POST /petclinic/api/owners/{ownerId}/pets"


def read_csv(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def fmt_int(n):
    return f"{int(n):,}".replace(",", "{,}")


def fmt_pct(x):
    return f"{100 * x:.1f}\\%"


def macro_name(*parts):
    """'pet-clinic', 'full', 'ops' -> \\NpetclinicFullOps (letters only, as LaTeX needs)."""
    out = "N"
    for p in parts:
        for word in p.replace("+", " plus ").replace("-", " ").replace("_", " ").split():
            out += word[:1].upper() + word[1:]
    return "\\" + "".join(ch for ch in out if ch.isalpha())


def main(data_dir, paper_dir):
    macros = {}

    # ---------------- parser / conformance / cost ----------------
    parser = read_csv(os.path.join(data_dir, "parser.csv"))
    conf = read_csv(os.path.join(data_dir, "conformance.csv"))
    cost = read_csv(os.path.join(data_dir, "cost.csv"))
    by_api = {(r["api"], r["generator"]): r for r in conf}

    macros[macro_name("specs")] = len(parser)
    macros[macro_name("ops", "total")] = fmt_int(sum(int(r["operations"]) for r in parser))
    macros[macro_name("refs", "total")] = fmt_int(sum(int(r["refs_in_spec"]) for r in parser))
    macros[macro_name("refs", "left")] = sum(int(r["refs_left_after_parse"]) for r in parser)
    macros[macro_name("allof", "total")] = sum(int(r["allof_in_spec"]) for r in parser)
    macros[macro_name("specs", "without", "examples")] = sum(1 for r in parser if int(r["examples_in_spec"]) == 0)
    macros[macro_name("patterns", "total")] = sum(int(r["patterns_in_spec"]) for r in parser)
    macros[macro_name("formats", "total")] = fmt_int(sum(int(r["formats_in_spec"]) for r in parser))
    macros[macro_name("recursive", "total")] = sum(int(r["recursive_schemas"]) for r in parser)
    macros[macro_name("parse", "ms", "max")] = max(float(r["parse_ms_median"]) for r in parser)
    biggest = max(parser, key=lambda r: int(r["refs_in_spec"]))
    macros[macro_name("refs", "max", "api")] = biggest["api"]
    macros[macro_name("refs", "max")] = fmt_int(biggest["refs_in_spec"])
    for gen in ("tool", "baseline"):
        ok = sum(int(by_api[(r["api"], gen)]["conforming"]) for r in parser)
        tot = sum(int(by_api[(r["api"], gen)]["inputs"]) for r in parser)
        macros[macro_name("conf", gen)] = fmt_pct(ok / tot)
        macros[macro_name("conf", gen, "inputs")] = fmt_int(tot)
        shares = [float(by_api[(r["api"], gen)]["share"]) for r in parser]
        macros[macro_name("conf", gen, "min")] = fmt_pct(min(shares))
        macros[macro_name("conf", gen, "below")] = sum(1 for s in shares if s < 1)
    viol = [r for r in read_csv(os.path.join(data_dir, "violations.csv")) if r["generator"] == "baseline"]
    total_v = sum(int(r["violations"]) for r in viol)
    fmt_v = sum(int(r["violations"]) for r in viol if r["kind"] in ("format", "pattern"))
    macros[macro_name("viol", "baseline")] = fmt_int(total_v)
    macros[macro_name("viol", "baseline", "format", "pattern")] = fmt_pct(fmt_v / total_v) if total_v else "0.0\\%"
    worst = min(parser, key=lambda r: float(by_api[(r["api"], "baseline")]["share"]))
    macros[macro_name("conf", "baseline", "worst", "api")] = worst["api"]
    macros[macro_name("gen", "us", "max")] = max(float(r["mean_us_per_request"]) for r in cost)
    macros[macro_name("gen", "us", "median")] = statistics.median(float(r["mean_us_per_request"]) for r in cost)

    rows = []
    for r in parser:
        rows.append(f"    {r['api']} & {r['operations']} & {fmt_int(r['refs_in_spec'])} & {r['allof_in_spec']} & "
                    f"{r['refs_left_after_parse']} & {float(r['parse_ms_median']):.1f} & "
                    f"{fmt_pct(float(by_api[(r['api'], 'baseline')]['share']))} & "
                    f"{fmt_pct(float(by_api[(r['api'], 'tool')]['share']))} \\\\")
    total = (f"    total & {macros[macro_name('ops', 'total')]} & {macros[macro_name('refs', 'total')]} & "
             f"{macros[macro_name('allof', 'total')]} & {macros[macro_name('refs', 'left')]} & & "
             f"{macros[macro_name('conf', 'baseline')]} & {macros[macro_name('conf', 'tool')]} \\\\")
    with open(os.path.join(paper_dir, "tables", "parser.tex"), "w") as f:
        f.write("%% Generated by src/eval/summarize.py from data/parser.csv and data/conformance.csv. Do not edit.\n")
        f.write("\\begin{table}[t]\n  \\caption{The parser reads all " + str(len(parser)) +
                " specifications and leaves no reference unresolved; the value generator keeps every VALID input "
                "inside its schema. \\emph{Ops}: operations. \\emph{\\$refs}, \\emph{allOf}: occurrences in the "
                "specification file. \\emph{Left}: \\$refs left after parsing. \\emph{ms}: median parse time of "
                "five runs. \\emph{Baseline}, \\emph{\\tool}: share of generated VALID parameter values and bodies "
                "that satisfy their schema (50 requests per operation).}\n  \\label{tab:parser}\n  \\footnotesize\n"
                "  \\begin{tabular}{lrrrrrrr}\n    \\toprule\n"
                "    API & Ops & \\$refs & allOf & Left & ms & Baseline & \\tool \\\\\n    \\midrule\n")
        f.write("\n".join(rows) + "\n    \\midrule\n" + total + "\n    \\bottomrule\n  \\end{tabular}\n\\end{table}\n")

    # ---------------- live runs ----------------
    live = {}
    for path in sorted(glob.glob(os.path.join(data_dir, "live", "*", "*.json"))):
        d = json.load(open(path))
        live.setdefault((d["api"], d["config"]), []).append(d)
    apis = sorted({a for a, _ in live})
    reps = min(len(v) for v in live.values())
    macros[macro_name("reps")] = reps
    macros[macro_name("live", "apis")] = len(apis)

    def mean(xs):
        return statistics.mean(xs)

    def sd(xs):
        return statistics.pstdev(xs)

    lines = []
    for api in apis:
        n_ops = live[(api, "full")][0]["operations"]
        budget = live[(api, "full")][0]["total_requests"]
        key = api.replace("-", "")
        macros[macro_name(key, "ops")] = n_ops
        macros[macro_name(key, "budget")] = fmt_int(budget)
        first = True
        for c in CONFIGS:
            runs = live[(api, c)]
            ops2 = [r["ops_with_2xx"] for r in runs]
            nom = [r["nominal_requests"] for r in runs]
            f5 = [r["unique_5xx"] for r in runs]
            union = len(set().union(*[set(r["faults"]) for r in runs]))
            macros[macro_name(key, c, "ops")] = f"{mean(ops2):.1f}"
            macros[macro_name(key, c, "cov")] = fmt_pct(mean(ops2) / n_ops)
            macros[macro_name(key, c, "nominal")] = f"{mean(nom):.1f}"
            macros[macro_name(key, c, "faults")] = f"{mean(f5):.1f}"
            macros[macro_name(key, c, "faults", "union")] = union
            label = f"\\multirow{{4}}{{*}}{{{api}}}" if first else ""
            first = False
            lines.append(f"    {label} & {CONFIG_LABEL[c]} & {mean(ops2):.1f} $\\pm$ {sd(ops2):.1f} & "
                         f"{fmt_pct(mean(ops2) / n_ops)} & {mean(nom):.1f} & {mean(f5):.1f} $\\pm$ {sd(f5):.1f} & {union} \\\\")
        lines.append("    \\midrule")
    lines = lines[:-1]
    with open(os.path.join(paper_dir, "tables", "live.tex"), "w") as f:
        f.write("%% Generated by src/eval/summarize.py from data/live/. Do not edit.\n")
        f.write("\\begin{table}[t]\n  \\caption{Each part of \\tool adds operations that reach a 2XX response. "
                f"Mean over {reps} runs, each on a freshly started API with the same budget of 20 requests per "
                "operation. \\emph{Ops 2XX}: operations with at least one 2XX response ($\\pm$ standard deviation). "
                "\\emph{Share}: Ops 2XX divided by all operations. \\emph{Nominal}: requests spent in the nominal "
                "phase (fewer is better). \\emph{5XX}: unique 5XX responses per run. \\emph{Union}: unique 5XX "
                f"over all {reps} runs.}}\n  \\label{{tab:live}}\n  \\footnotesize\n"
                "  \\begin{tabular}{llrrrrr}\n    \\toprule\n"
                "    API & Configuration & Ops 2XX & Share & Nominal & 5XX & Union \\\\\n    \\midrule\n")
        f.write("\n".join(lines) + "\n    \\bottomrule\n  \\end{tabular}\n\\end{table}\n")

    # motivating example: one operation, all runs of one configuration
    for c in ("baseline", "full"):
        runs = live.get(("pet-clinic", c), [])
        stats = [r["per_op"][MOTIVATING_OP] for r in runs]
        req = sum(s["requests"] for s in stats)
        macros[macro_name("motiv", c, "requests")] = fmt_int(req)
        macros[macro_name("motiv", c, "ok")] = fmt_int(sum(s["2xx"] for s in stats))
        macros[macro_name("motiv", c, "client")] = fmt_int(sum(s["4xx"] for s in stats))
        macros[macro_name("motiv", c, "server")] = fmt_int(sum(s["5xx"] for s in stats))
        macros[macro_name("motiv", c, "runs", "ok")] = sum(1 for s in stats if s["2xx"])

    # code size (non-blank, non-comment lines) of the component and of its tests
    src = os.path.join(os.path.dirname(__file__), "..")

    def loc(pattern):
        n = 0
        for path in glob.glob(os.path.join(src, pattern)):
            n += sum(1 for line in open(path) if line.strip() and not line.strip().startswith("#"))
        return n
    macros[macro_name("loc", "parser")] = loc("restleague/spec/parser.py")
    macros[macro_name("loc", "values")] = loc("restleague/spec/values.py")
    macros[macro_name("loc", "deps")] = loc("restleague/spec/deps.py")
    macros[macro_name("loc", "spec")] = fmt_int(loc("restleague/spec/*.py"))
    macros[macro_name("loc", "tests")] = loc("tests/*.py")
    macros[macro_name("loc", "eval")] = fmt_int(loc("eval/*.py"))
    sys.path.insert(0, src)
    from tests.parser_levels import LEVELS
    macros[macro_name("levels")] = len(LEVELS)

    with open(os.path.join(data_dir, "numbers.tex"), "w") as f:
        f.write("%% Generated by src/eval/summarize.py. Do not edit; rerun the script.\n")
        for name, value in macros.items():
            f.write(f"\\newcommand{{{name}}}{{{value}\\xspace}}\n")  # xspace: keep the space after it
    print(f"wrote {len(macros)} macros, tables/parser.tex, tables/live.tex")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
